"""The generated module's source (P6, K4, V1): plain Python, deterministic (B5), importing the run time by its absolute
name (`texpkg`), which the embedding step later points at the private copy (1.5).

The module is `acme_tex/{__init__,_bound,_version,errors}.py` and `kinds/{__init__,<kind>}.py`; the declaration is
imported from `acme_tex._declaration`, so its classes are real classes a type checker reads (K4).
"""

import copy
import inspect
import typing
from collections.abc import Iterator
from typing import Annotated

from texpkg import errors
from texpkg.contracts import Contracts
from texpkg.declaration import Distribution, Kind, reachable
from texpkg.errors import DeclarationError

_HEADER = '"""Generated by texpkg-build from the declaration. Do not edit."""\n'
_FOREIGN = ("builtins", "typing", "types", "collections", "texmodel", "enum", "pydantic")


def render_sty(dist: Distribution, version: str) -> dict[str, str]:
    """The `.sty` of the distribution's own package, rendered at `version` (P4, V1). The author's object is left as it
    is. A base's was rendered when the base was built."""
    package = copy.copy(dist.package)
    package.version = version
    return {f"{package.name}.sty": package.render()}


def error_names() -> tuple[str, ...]:
    return tuple(
        sorted(name for name, cls in inspect.getmembers(errors, inspect.isclass) if issubclass(cls, errors.TexpkgError))
    )


def _types(hint: object) -> Iterator[type]:
    """The classes a field's annotation names that the declaration defines: a `Choice`, a bounded length (P24)."""
    if typing.get_origin(hint) is Annotated:
        yield from _types(typing.get_args(hint)[0])
    elif args := typing.get_args(hint):
        for arg in args:
            yield from _types(arg)
    elif isinstance(hint, type) and hint.__module__.split(".")[0] not in _FOREIGN:
        yield hint


def exported(kind: Kind) -> tuple[type, ...]:
    """The classes a kind module exports: the components its trees are made of, and the value types they use, once each
    and in the order met."""
    found: dict[type, None] = {}
    for cls in reachable(kind.model):
        found[cls] = None
        for arg in cls.__tm_args__:
            found.update(dict.fromkeys(_types(arg.hint)))
    return tuple(found)


def _import_from(dist: Distribution, cls: type) -> str:
    """`from .._declaration.model import Deck as Deck` for `cls`, relative to `kinds/<kind>.py`, wherever in the chain
    it is declared."""
    for owner in dist.chain():
        prefix = owner.declared_in
        if cls.__module__ == prefix or cls.__module__.startswith(prefix + "."):
            if "." in cls.__qualname__:
                break
            where = "_declaration" if owner is dist else f"_embedded.{owner.module}._declaration"
            return f"from ..{where}{cls.__module__.removeprefix(prefix)} import {cls.__name__} as {cls.__name__}"
    raise DeclarationError(
        f"{cls.__module__}.{cls.__qualname__} is not a top-level class of the declaration package or of a base",
        code="TP-B002",
        path=cls.__qualname__,
        hint="declare it at module level inside the package named by declared_in, so the module can export it",
    )


def _kind_source(dist: Distribution, kind: Kind) -> str:
    classes = exported(kind)
    imports = sorted({_import_from(dist, cls) for cls in classes})
    root = kind.model.__name__
    return "\n".join(
        [
            _HEADER,
            "from typing import Any, Final, Literal",
            "",
            "from texpkg.contracts import Changes",
            "",
            "from .. import _bound",
            *imports,
            "",
            f"NAME: Final = {kind.name!r}",
            f"_api = _bound.RELEASE.kind(NAME, {root})",
            "",
            "",
            'def schema(mode: Literal["validation", "serialization"] = "validation") -> dict[str, Any]:',
            "    return _api.schema(mode)",
            "",
            "",
            f"def example() -> {root}:",
            "    return _api.example()",
            "",
            "",
            "def variants() -> tuple[str, ...]:",
            "    return _api.variants()",
            "",
            "",
            "def changes(old: int, new: int) -> Changes:",
            "    return _api.changes(old, new)",
            "",
        ]
    )


def sources(dist: Distribution, pointer_attr: str, version: str, contracts: Contracts) -> dict[str, str]:
    """The generated files by path inside the module, for `dist` released at `version`. `pointer_attr` is the name
    `[tool.texpkg] distribution` gives the declaration inside its package."""
    names = [k.name for k in dist.kinds]
    c = contracts
    sty = render_sty(dist, version)
    return (
        {f"_sty/{name}": text for name, text in sty.items()}
        | {
            "__init__.py": "\n".join(
                [
                    _HEADER,
                    "from typing import Final",
                    "",
                    "from . import errors, kinds",
                    "from ._version import CONTRACTS, VERSION",
                    "",
                    "__version__: Final = VERSION",
                    '__all__ = ["CONTRACTS", "__version__", "errors", "kinds"]',
                    "",
                ]
            ),
            "_version.py": "\n".join(
                [
                    _HEADER,
                    "from typing import Final",
                    "",
                    "from texpkg.contracts import Contracts, Pair, Triple",
                    "",
                    f"VERSION: Final = {version!r}",
                    "CONTRACTS: Final = Contracts(",
                    f"    Triple({c.data.current}, {c.data.revision}, {c.data.age}),",
                    f"    Triple({c.interface.current}, {c.interface.revision}, {c.interface.age}),",
                    f"    Pair({c.output.current}, {c.output.revision}),",
                    ")",
                    "",
                ]
            ),
            "_bound.py": "\n".join(
                [
                    _HEADER,
                    "from importlib.resources import files",
                    "from typing import Final",
                    "",
                    "from texpkg._internal.release import Release",
                    "",
                    f"from ._declaration import {pointer_attr}",
                    "from ._version import CONTRACTS, VERSION",
                    "",
                    f"_NAMES: Final = ({''.join(f'{n!r}, ' for n in sty).strip()})",
                    "STY: Final = {",
                    '    name: files(__package__).joinpath("_sty", name).read_text(encoding="utf-8")',
                    "    for name in _NAMES",
                    "}",
                    f"RELEASE: Final = Release({pointer_attr}, VERSION, CONTRACTS, STY)",
                    "",
                ]
            ),
            "errors.py": "\n".join(
                [
                    _HEADER,
                    "from texpkg.errors import (",
                    *(f"    {name} as {name}," for name in error_names()),
                    ")",
                    "",
                ]
            ),
            "kinds/__init__.py": "\n".join(
                [
                    _HEADER,
                    "from collections.abc import Mapping",
                    "",
                    "from texpkg.protocol import KindModule",
                    "",
                    f"from . import {', '.join(names)}" if names else "",
                    "",
                    "",
                    "def names() -> tuple[str, ...]:",
                    f"    return ({''.join(f'{n!r}, ' for n in names).strip()})" if names else "    return ()",
                    "",
                    "",
                    "def modules() -> Mapping[str, KindModule]:",
                    f"    return {{{', '.join(f'{n!r}: {n}' for n in names)}}}",
                    "",
                ]
            ),
        }
        | {f"kinds/{kind.name}.py": _kind_source(dist, kind) for kind in dist.kinds}
    )
