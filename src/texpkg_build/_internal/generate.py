"""The generated module's source (P6, K4, V1): plain Python, deterministic (B5), importing the run time by its absolute
name (`texpkg`), which the embedding step later points at the private copy (1.5).

The module is `acme_tex/{__init__,_bound,_version,errors}.py`, `kinds/{__init__,<kind>}.py` and `_sty/<name>.sty`; the
declaration is imported from `acme_tex._declaration`, so its classes are real classes a type checker reads (K4).
"""

import copy
import dataclasses
import importlib
import inspect
import textwrap
import typing
from collections.abc import Iterator, Sequence
from typing import Annotated, Any, cast

from pydantic import BaseModel, TypeAdapter
from texmodel.components import Passthrough

from texpkg import errors
from texpkg._internal import provenance_tex
from texpkg.contracts import Contracts
from texpkg.declaration import Distribution, Kind, raw_holes, reachable
from texpkg.errors import DeclarationError

_HEADER = '"""Generated by texpkg-build from the declaration. Do not edit."""\n'
_VALUES = "texmodel.types"  # the value types a field is annotated with: a consumer's own copy would be refused
_FOREIGN = ("builtins", "typing", "types", "collections", "texmodel", "enum", "pydantic")


def render_sty(dist: Distribution, version: str) -> dict[str, str]:
    """The `.sty` of the distribution's own package, rendered at `version` (P4, V1). The author's object is left as it
    is. A base's was rendered when the base was built."""
    package = copy.deepcopy(dist.package)  # a copy that shares no list with the author's: the block is added to it
    if not package.prefix:
        raise DeclarationError(
            f"package {package.name} has no prefix, so it cannot declare its provenance command",
            code="TP-B011",
            path=package.name,
            hint='give the Package a prefix: Package("acme", prefix="ac")',
        )
    package.version = version
    package.library("texpkg-provenance", provenance_tex.declarations(package.prefix, package.name, version))
    return {f"{package.name}.sty": package.render()}


def error_names() -> tuple[str, ...]:
    return tuple(
        sorted(name for name, cls in inspect.getmembers(errors, inspect.isclass) if issubclass(cls, errors.TexpkgError))
    )


def _types(hint: object) -> Iterator[type]:
    """The classes a field's annotation names that the declaration defines: a `Choice`, a bounded length (P24)."""
    if typing.get_origin(hint) is Annotated:
        yield from _types(typing.get_args(hint)[0])
    elif args := typing.get_args(hint):
        for arg in args:
            yield from _types(arg)
    elif isinstance(hint, type) and (hint.__module__.split(".")[0] not in _FOREIGN or hint.__module__ == _VALUES):
        yield hint


def exported(kind: Kind) -> tuple[type, ...]:
    """The classes a kind module exports: the components its trees are made of, the value types they use and the
    comment classes of their packages, once each and in the order met. (`Comment` itself is texmodel's: see
    `_kind_source`.)"""
    found: dict[type, None] = {}
    for cls in reachable(kind.model):
        found[cls] = None
        package = getattr(cls, "__tm_package__", None)  # a comment class belongs to the package of the node holding it
        found.update(dict.fromkeys(package.comments if package else ()))
        for arg in cls.__tm_args__:
            found.update(dict.fromkeys(_types(arg.hint)))
    found.update(dict.fromkeys(kind.settable))
    for cls in tuple(found):  # a value's payload is built by the consumer too: `Ink(CMYK(...))`
        if (value := getattr(cls, "__tm_kind__", None)) is not None:
            found.update(dict.fromkeys(_types(value.python)))
    if any(hole.endswith(".Passthrough") for hole in raw_holes(kind.model)):
        found[Passthrough] = None
    return tuple(found)


def _import_from(dist: Distribution, cls: type) -> str:
    """`from .._declaration.model import Deck as Deck` for `cls`, relative to `kinds/<kind>.py`, wherever in the chain
    it is declared."""
    if cls.__module__.split(".")[0] == "texmodel":  # imported by name: the build points it at the embedded copy
        return f"from {cls.__module__} import {cls.__name__} as {cls.__name__}"
    for owner in dist.chain():
        prefix = owner.declared_in
        if cls.__module__ == prefix or cls.__module__.startswith(prefix + "."):
            if "." in cls.__qualname__:
                break
            where = "_declaration" if owner is dist else f"_embedded.{owner.module}._declaration"
            return f"from ..{where}{cls.__module__.removeprefix(prefix)} import {cls.__name__} as {cls.__name__}"
    raise DeclarationError(
        f"{cls.__module__}.{cls.__qualname__} is not a top-level class of the declaration package or of a base",
        code="TP-B002",
        path=cls.__qualname__,
        hint="declare it at module level inside the package named by declared_in, so the module can export it",
    )


def _module(body: str) -> str:
    return _HEADER + "\n" + textwrap.dedent(body).strip() + "\n"


def _kind_source(dist: Distribution, kind: Kind) -> str:
    lines = {_import_from(dist, cls) for cls in exported(kind)}
    lines |= {f"from {cls.__module__} import {cls.__name__} as {cls.__name__}" for cls in kind.preamble}
    lines.add(
        "from texmodel.body import Comment as Comment"
    )  # the embedded texmodel's, which the grammar checks against
    imports = "\n        ".join(sorted(lines))  # the template's indent
    settings = " | ".join(c.__name__ for c in kind.settable) or "Never"
    options = f"Literal[{', '.join(repr(o) for o in kind.options)}]" if kind.options else "Never"
    root = kind.model.__name__
    return _module(f"""
        from collections.abc import Mapping, Sequence
        from pathlib import Path
        from typing import Any, Final, Literal, Never

        from texmodel.preamble import PreambleSlots

        from texpkg.contracts import Changes
        from texpkg.document import Document
        from texpkg.migration import DefaultChange, Migration

        from .. import _bound
        {imports}

        NAME: Final = {kind.name!r}
        _api = _bound.RELEASE.kind(NAME, {root})


        def load(
            path: Path | str,
            *,
            migrations: Sequence[Migration] = (),
            default_changes: DefaultChange | Mapping[str, DefaultChange] = DefaultChange.FOLLOW,
        ) -> Document[{root}]:
            return _api.load(path, migrations, default_changes)


        def create(
            path: Path | str,
            tree: {root},
            *,
            settings: Sequence[{settings}] = (),
            options: Sequence[{options}] = (),
            preamble: PreambleSlots | None = None,
        ) -> Document[{root}]:
            return _api.create(path, tree, settings=settings, options=options, preamble=preamble)


        def schema(mode: Literal["validation", "serialization"] = "validation") -> dict[str, Any]:
            return _api.schema(mode)


        def example() -> {root}:
            return _api.example()


        def variants() -> tuple[str, ...]:
            return _api.variants()


        def changes(old: int, new: int) -> Changes:
            return _api.changes(old, new)
    """)


def _plain(value: object) -> object | None:
    """`value` as JSON: what JSON holds, and a dataclass or pydantic instance as `{"$class": name, ...fields}`, or
    `{"$class": name, "value": text}` when it has a text form (a `Length`). An enum member is refused unless it is a
    field. `NotImplemented` for anything else."""
    if type(value) in (type(None), bool, int, float, str):
        return value
    if isinstance(value, list | tuple):
        items = [_plain(v) for v in cast("Sequence[object]", value)]
        return NotImplemented if NotImplemented in items else items
    if isinstance(value, dict):
        pairs = {k: _plain(v) for k, v in cast("dict[object, object]", value).items()}
        return NotImplemented if NotImplemented in pairs.values() or not all(type(k) is str for k in pairs) else pairs
    if isinstance(value, BaseModel) or (dataclasses.is_dataclass(value) and not isinstance(value, type)):
        dumped = TypeAdapter(type(value)).dump_python(value, mode="json")
        return {"$class": type(value).__qualname__, **(dumped if isinstance(dumped, dict) else {"value": dumped})}
    return NotImplemented


def public_values(dist: Distribution) -> dict[str, Any]:
    """The constants of `dist.public` as JSON, by name in `__all__` order (P31)."""

    def refuse(what: str, hint: str) -> DeclarationError:
        return DeclarationError(f"{dist.public} {what}", code="TP-B014", path=dist.public, hint=hint)

    module = importlib.import_module(dist.public)
    listed: object = getattr(module, "__all__", None)
    if not isinstance(listed, list | tuple) or not all(isinstance(n, str) for n in cast("Sequence[object]", listed)):
        raise refuse("has no __all__ listing the names to publish", "write __all__ = ['BLEED', ...]")
    out: dict[str, Any] = {}
    for name in cast("Sequence[str]", listed):
        if not hasattr(module, name):
            raise refuse(f"lists {name!r}, which it does not define", "define it or remove it from __all__")
        value = getattr(module, name)
        if (plain := _plain(value)) is NotImplemented:
            raise refuse(
                f"publishes {name!r}, a {type(value).__name__}, which cannot be written as JSON",
                "publish JSON-like values, or dataclass or pydantic instances",
            )
        out[name] = plain
    return out


def _public_source(dist: Distribution) -> str:
    names = list(public_values(dist))
    where = dist.public.removeprefix(dist.declared_in)
    imports = "".join(f"from ._declaration{where} import {n} as {n}\n" for n in names)
    return _module(imports + "\n__all__ = [" + ", ".join(repr(n) for n in names) + "]")


def _tuple(items: list[str]) -> str:
    return "(" + "".join(f"{item!r}, " for item in items).strip() + ")"


def sources(dist: Distribution, pointer: str, version: str, contracts: Contracts) -> dict[str, str]:
    """The generated files by path inside the module, for `dist` released at `version`. `pointer` is the
    `module:attribute` of `[tool.texpkg] distribution`: where the declaring package holds the declaration."""
    module, _, pointer_attr = pointer.partition(":")
    where = module.removeprefix(dist.declared_in)  # "" when the declaration is the package's `__init__`
    offered = dist.kinds_offered()
    names = [k.name for k in offered]
    sty = render_sty(dist, version)
    c = contracts
    imports = f"from . import {', '.join(names)}" if names else ""
    all_public = '\n                    "public",' if dist.public else ""  # the template's indent
    public = {"public.py": _public_source(dist)} if dist.public else {}
    base = dist.base
    base_import = f"from ._embedded.{base.module} import _bound as _base" if base else ""
    base_sty = "**_base.STY, " if base else ""
    base_release = "(_base.RELEASE,), " if base else "(), "
    return (
        {f"_sty/{name}": text for name, text in sty.items()}
        | public
        | {
            "__init__.py": _module(f"""
                import datetime
                from collections.abc import Mapping, Sequence
                from pathlib import Path
                from typing import Any, Final

                from texpkg.document import Document
                from texpkg.migration import DefaultChange, Migrated, Migration, Unresolved, migration

                from . import errors, kinds{", public" if dist.public else ""}
                from ._bound import RELEASE
                from ._version import CONTRACTS, VERSION

                __version__: Final = VERSION
                dist: Final = RELEASE.dist  # for a package built on this one (P14)
                __all__ = [
                    "CONTRACTS",
                    "DefaultChange",
                    "Migrated",
                    "Unresolved",
                    "__version__",
                    "dist",
                    "errors",
                    "export",
                    "kinds",
                    "load",
                    "migration",{all_public}
                ]


                def export(
                    dest: Path | str, *, now: datetime.datetime | None = None, stamp: str | None = None
                ) -> tuple[Path, ...]:
                    return RELEASE.export(dest, now, stamp)


                def load(
                    path: Path | str,
                    *,
                    migrations: Sequence[Migration] = (),
                    default_changes: DefaultChange | Mapping[str, DefaultChange] = DefaultChange.FOLLOW,
                ) -> Document[Any]:
                    return RELEASE.load(path, migrations, default_changes)
            """),
            "_version.py": _module(f"""
                from typing import Final

                from texpkg.contracts import Contracts, Pair, Triple

                VERSION: Final = {version!r}
                CONTRACTS: Final = Contracts(
                    Triple({c.data.current}, {c.data.revision}, {c.data.age}),
                    Triple({c.interface.current}, {c.interface.revision}, {c.interface.age}),
                    Pair({c.output.current}, {c.output.revision}),
                    {c.base_data!r},
                )
            """),
            "_bound.py": _module(f"""
                from importlib.resources import files
                from typing import Final

                from texpkg._internal.release import Release

                from ._declaration{where} import {pointer_attr}
                from ._version import CONTRACTS, VERSION
                {base_import}

                _NAMES: Final = {_tuple(list(sty))}
                _SNAPSHOTS: Final = files(__package__).joinpath("_contracts")
                _OWN: Final = {{
                    name: files(__package__).joinpath("_sty", name).read_text(encoding="utf-8") for name in _NAMES
                }}
                STY: Final = {{{base_sty}**_OWN}}
                RELEASE: Final = Release({pointer_attr}, VERSION, CONTRACTS, STY, {base_release}_SNAPSHOTS)
            """),
            "errors.py": _module(
                "from texpkg.errors import (\n" + "".join(f"    {name} as {name},\n" for name in error_names()) + ")\n"
            ),
            "kinds/__init__.py": _module(f"""
                from collections.abc import Mapping

                from texpkg.protocol import KindModule

                {imports}


                def names() -> tuple[str, ...]:
                    return {_tuple(names)}


                def modules() -> Mapping[str, KindModule]:
                    return {{{", ".join(f"{n!r}: {n}" for n in names)}}}
            """),
        }
        | {f"kinds/{kind.name}.py": _kind_source(dist, kind) for kind in offered}
    )
