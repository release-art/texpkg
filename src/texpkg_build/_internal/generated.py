"""Declaration modules generated from data (K4): committed, and refused when stale.

`[tool.texpkg] generate = "module:function"` names a pure `function(root) -> {path: source}`, where `root` is the
declaring package's directory and each path is relative to it. `texpkg-build generate` writes the files; the build runs
the function again and refuses a file that is missing, differs (stale or hand-edited), or is left over from an earlier
run. The function must not import a module that imports the files it produces, as the declaration does: keep the
declaration in a module of its own (`pkg.declaration:dist`) and `pkg/__init__.py` free of imports, and the function can
share the package's pure modules.
"""

import importlib
import pathlib
from collections.abc import Callable, Mapping
from typing import cast

from texpkg.errors import DeclarationError

from .isolate import Isolation

# `# fmt: off` keeps a formatter from making a file differ from what the generator writes.
HEADER = "# Generated by texpkg-build generate. Do not edit.\n# fmt: off\n"


def package_directory(source: pathlib.Path, module: str) -> pathlib.Path:
    """The directory of the declaring package, found without importing it: `module` itself when it is a package
    (`pkg:dist`), else the package that holds it (`pkg.declaration:dist`), as `Distribution(declared_in)` is."""
    path = source.joinpath(*module.split("."))
    return path if path.is_dir() else path.parent


def _function(pointer: str, isolation: Isolation) -> Callable[[pathlib.Path], Mapping[str, str]]:
    module, _, attr = pointer.partition(":")
    isolation.forget(module.split(".")[0])
    found = getattr(importlib.import_module(module), attr, None)
    if not callable(found):
        raise DeclarationError(
            f"{pointer} is not a function",
            code="TP-B013",
            path=pointer,
            hint='write generate = "module:function", a function of the declaring package\'s directory',
        )
    return cast("Callable[[pathlib.Path], Mapping[str, str]]", found)


def _checked(pointer: str, produced: Mapping[str, str]) -> dict[str, str]:
    """The files with their header, each a relative `.py` path that stays inside the package."""
    out: dict[str, str] = {}
    for path, text in produced.items():
        parts = pathlib.PurePosixPath(path)
        if parts.is_absolute() or ".." in parts.parts or parts.suffix != ".py":
            raise DeclarationError(
                f"{pointer} returned {path!r}: not a relative .py path inside the package",
                code="TP-B013",
                path=pointer,
                hint="return {'_kinds/short.py': source, ...}",
            )
        out[path] = HEADER + text
    return out


def produce(pointer: str, root: pathlib.Path, isolation: Isolation) -> dict[str, str]:
    """What the generator writes, run twice: the same bytes both times (B5)."""
    function = _function(pointer, isolation)
    first = _checked(pointer, function(root))
    if first != _checked(pointer, function(root)):
        raise DeclarationError(
            f"{pointer} returned something different the second time",
            code="TP-B013",
            path=pointer,
            hint="generated source is a function of the data alone: no clock, hash or set order",
        )
    return first


def _left_over(root: pathlib.Path, produced: Mapping[str, str]) -> list[str]:
    """Files under `root` that carry the header but are no longer produced."""
    return sorted(
        found
        for path in root.rglob("*.py")
        if (found := path.relative_to(root).as_posix()) not in produced
        and path.read_text(encoding="utf-8").startswith(HEADER)
    )


def drift(root: pathlib.Path, produced: Mapping[str, str]) -> list[str]:
    """What differs between the files in `root` and `produced`, as lines for a message."""
    lines: list[str] = []
    for path, text in sorted(produced.items()):
        target = root / path
        if not target.is_file():
            lines.append(f"{path}: missing")
        elif target.read_text(encoding="utf-8") != text:
            lines.append(f"{path}: differs from what the generator writes")
    return lines + [f"{path}: no longer generated" for path in _left_over(root, produced)]


def write(root: pathlib.Path, produced: Mapping[str, str]) -> list[str]:
    """Bring `root` to `produced`: write what differs and remove generated files that are no longer produced (only
    ones that carry the header). Returns the paths touched."""
    touched: list[str] = []
    for path, text in sorted(produced.items()):
        target = root / path
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
            touched.append(path)
    for path in _left_over(root, produced):
        (root / path).unlink()
        touched.append(path)
    return touched


def refuse_if_stale(pointer: str, root: pathlib.Path, produced: Mapping[str, str]) -> None:
    """The build's gate: the committed files are what the generator writes."""
    if lines := drift(root, produced):
        raise DeclarationError(
            f"the files generated by {pointer} are not current:\n  " + "\n  ".join(lines),
            code="TP-B012",
            path=pointer,
            hint="run texpkg-build generate and commit the result",
        )
